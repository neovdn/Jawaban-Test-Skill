-- Soal No 1
CREATE DATABASE IF NOT EXISTS test_it;

USE test_it;

-- (a) MSBARANG
CREATE TABLE MSBARANG (
  KODE_BARANG  VARCHAR(5)   NOT NULL,
  NAMA_BARANG  VARCHAR(50)  NOT NULL,
  SATUAN       VARCHAR(5)   NOT NULL,
  KATEGORI     VARCHAR(10)  NOT NULL,

  PRIMARY KEY (KODE_BARANG)
);

-- (b) TRMUTASIHD
CREATE TABLE TRMUTASIHD (
  NO_TRANSAKSI     VARCHAR(5)   NOT NULL,
  TANGGAL          DATE         NOT NULL,
  JENIS_TRANSAKSI  VARCHAR(10)  NOT NULL,  -- 'MASUK' / 'KELUAR'
  KATEGORI         VARCHAR(10)  NOT NULL,

  PRIMARY KEY (NO_TRANSAKSI),

  CONSTRAINT chk_jenis_transaksi
    CHECK (JENIS_TRANSAKSI IN ('MASUK','KELUAR'))
);

-- (c) TRMUTASIDT
CREATE TABLE TRMUTASIDT (
  NO_TRANSAKSI  VARCHAR(5)  NOT NULL,
  KODE_BARANG   VARCHAR(5)  NOT NULL,
  QTY           INT         NOT NULL,

  PRIMARY KEY (NO_TRANSAKSI, KODE_BARANG),

  CONSTRAINT fk_dt_hd
    FOREIGN KEY (NO_TRANSAKSI)
    REFERENCES TRMUTASIHD (NO_TRANSAKSI)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

  CONSTRAINT fk_dt_barang
    FOREIGN KEY (KODE_BARANG)
    REFERENCES MSBARANG (KODE_BARANG)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,

  CONSTRAINT chk_qty
    CHECK (QTY > 0)
);
