-- 3.1 Stok barang per item periode Januari - Februari 2021
SELECT
    b.KODE_BARANG,
    b.NAMA_BARANG,
    b.SATUAN,
    b.KATEGORI,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'MASUK'  THEN t.QTY END), 0) AS TRANS_MASUK,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'KELUAR' THEN t.QTY END), 0) AS TRANS_KELUAR,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'MASUK'  THEN t.QTY END), 0)
  - COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'KELUAR' THEN t.QTY END), 0) AS STOK_AKHIR
FROM MSBARANG b
LEFT JOIN (
    SELECT d.KODE_BARANG, h.JENIS_TRANSAKSI, d.QTY
    FROM TRMUTASIDT d
    JOIN TRMUTASIHD h ON h.NO_TRANSAKSI = d.NO_TRANSAKSI
    WHERE h.TANGGAL >= '2021-01-01'
      AND h.TANGGAL <  '2021-03-01'
) t ON t.KODE_BARANG = b.KODE_BARANG
GROUP BY b.KODE_BARANG, b.NAMA_BARANG, b.SATUAN, b.KATEGORI
ORDER BY b.KATEGORI DESC, b.KODE_BARANG;

-- 3.2 Stok barang per kelompok
SELECT
    b.KATEGORI,
    b.SATUAN,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'MASUK'  THEN t.QTY END), 0) AS TRANS_MASUK,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'KELUAR' THEN t.QTY END), 0) AS TRANS_KELUAR,
    COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'MASUK'  THEN t.QTY END), 0)
  - COALESCE(SUM(CASE WHEN t.JENIS_TRANSAKSI = 'KELUAR' THEN t.QTY END), 0) AS STOK_AKHIR
FROM MSBARANG b
LEFT JOIN (
    SELECT d.KODE_BARANG, h.JENIS_TRANSAKSI, d.QTY
    FROM TRMUTASIDT d
    JOIN TRMUTASIHD h ON h.NO_TRANSAKSI = d.NO_TRANSAKSI
    WHERE h.TANGGAL >= '2021-01-01'
      AND h.TANGGAL <  '2021-03-01'
) t ON t.KODE_BARANG = b.KODE_BARANG
GROUP BY b.KATEGORI, b.SATUAN
ORDER BY b.KATEGORI DESC, b.SATUAN;

-- 3.3 Barang dengan Transaksi Keluar tertinggi per kelompok
WITH keluar_per_barang AS (
    SELECT
        b.KATEGORI,
        b.SATUAN,
        b.KODE_BARANG,
        b.NAMA_BARANG,
        COALESCE(SUM(t.QTY), 0) AS TRANS_KELUAR
    FROM MSBARANG b
    LEFT JOIN (
        SELECT d.KODE_BARANG, d.QTY
        FROM TRMUTASIDT d
        JOIN TRMUTASIHD h ON h.NO_TRANSAKSI = d.NO_TRANSAKSI
        WHERE h.JENIS_TRANSAKSI = 'KELUAR'
          AND h.TANGGAL >= '2021-01-01'
          AND h.TANGGAL <  '2021-03-01'
    ) t ON t.KODE_BARANG = b.KODE_BARANG
    GROUP BY b.KATEGORI, b.SATUAN, b.KODE_BARANG, b.NAMA_BARANG
),
ranked AS (
    SELECT
        k.*,
        RANK() OVER (
            PARTITION BY k.KATEGORI, k.SATUAN
            ORDER BY k.TRANS_KELUAR DESC
        ) AS rnk
    FROM keluar_per_barang k
)
SELECT KATEGORI, SATUAN, KODE_BARANG, NAMA_BARANG, TRANS_KELUAR
FROM ranked
WHERE rnk = 1
  AND TRANS_KELUAR > 0
ORDER BY KATEGORI DESC, SATUAN;
